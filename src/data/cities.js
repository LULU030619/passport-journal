export const CITIES = RAW.map(([name, en, country, cc, lat, lng]) => ({
  name,
  en,
  country,
  countryCode: cc,
  lat,
  lng,
}));

/** 中英文都能搜，最多返回 8 条。 */
export function searchCities(q) {
  const key = (q || "").trim().toLowerCase();
  if (!key) return [];
  const hits = CITIES.filter(
    (c) =>
      c.name.includes(key) ||
      c.en.toLowerCase().includes(key) ||
      c.country.includes(key)
  );
  // 名字开头匹配的排前面
  hits.sort((a, b) => {
    const sa = a.name.startsWith(key) || a.en.toLowerCase().startsWith(key) ? 0 : 1;
    const sb = b.name.startsWith(key) || b.en.toLowerCase().startsWith(key) ? 0 : 1;
    return sa - sb;
  });
  return hits.slice(0, 8);
}
